import { AsyncLocalStorage } from 'node:async_hooks';
import { PrismaClient } from '@prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';

/**
 * Shared Prisma Client for BOTH environments:
 *  - Local Node dev (against Docker Postgres)
 *  - Cloudflare Workers production (against Neon, over TCP via cloudflare:sockets)
 *
 * We use the node-postgres (`pg`) driver adapter because it works in both places:
 *  - Node/dev: `pg` opens a normal TCP connection to localhost:5432
 *  - Workers: `pg` uses Cloudflare's `connect()` (from `cloudflare:sockets`) when
 *    the `nodejs_compat` compatibility flag is enabled.
 *
 * ── Why the client is PER REQUEST ──────────────────────────────────────────
 * Cloudflare's TCP socket docs are explicit:
 *
 *   "TCP sockets cannot be created in global scope and shared across requests.
 *    You should always create TCP sockets within a handler (ex: fetch())."
 *
 * `pg` keeps connections in an internal pool, so a module-level singleton
 * PrismaClient hands request A's socket to request B. The Workers runtime
 * refuses that I/O, the awaiting promise never settles, and the request is
 * killed with:
 *
 *   "The Workers runtime canceled this request because it detected that your
 *    Worker's code had hung and would never generate a response."
 *
 * That response is generated by the edge, so it carries NO CORS headers — which
 * is why the browser reports it as "blocked by CORS policy: No
 * 'Access-Control-Allow-Origin' header is present on the requested resource".
 *
 * The fix (matching Prisma's own Cloudflare Workers guide) is to create the
 * adapter + client inside the request and disconnect it when the request ends.
 * `prismaScope` (src/middleware/prismaScope.ts) opens a scope per request and
 * the `prisma` proxy below resolves to that request's client through
 * AsyncLocalStorage, so no route file had to change.
 */

/** Per-request holder. The client is created lazily on first use. */
export interface PrismaScope {
  client: PrismaClient | null;
  disposed: boolean;
}

const scopeStorage = new AsyncLocalStorage<PrismaScope>();

/** Client used outside any request (scripts, CLI tools, local `npm run dev`). */
let _fallbackClient: PrismaClient | null = null;

/** Create an empty scope for one incoming request. */
export function createScope(): PrismaScope {
  return { client: null, disposed: false };
}

/** Run the rest of the middleware chain inside `scope`. */
export function runInScope<T>(scope: PrismaScope, fn: () => T): T {
  return scopeStorage.run(scope, fn);
}

/**
 * Close the scope's connection pool. Safe to call more than once.
 *
 * Called as the response finishes/closes: on Workers a socket may not outlive
 * its request, and every open socket counts against the connection limit.
 */
export function disposeScope(scope: PrismaScope): void {
  if (scope.disposed) return;
  scope.disposed = true;

  const client = scope.client;
  scope.client = null;

  if (client) {
    // Fire-and-forget: the response is already sent, we just release sockets.
    void Promise.resolve(client.$disconnect()).catch(() => {});
  }
}

/**
 * Neon (and some poolers) advertise `channel_binding=require`, which the
 * Cloudflare TCP socket / Neon endpoint does not support and which causes
 * "Connection terminated unexpectedly" on Workers. Strip it, and drop any
 * dangling separators left behind.
 */
function sanitizeConnectionString(raw: string): string {
  let url = raw.trim();
  url = url.replace(/[?&]channel_binding=[^&]*/gi, '');
  url = url.replace(/\?&/, '?');
  url = url.replace(/[?&]$/, '');
  return url;
}

function createClient(): PrismaClient {
  const raw = process.env.DATABASE_URL || '';
  if (!raw) {
    throw new Error('DATABASE_URL is not set (configure it as a Worker secret / .env)');
  }

  const connectionString = sanitizeConnectionString(raw);
  const adapter = new PrismaPg({
    connectionString,
    // The pool only ever lives for a single request (see prismaScope), so keep
    // it small and fail fast instead of leaving a request hanging on a socket
    // that will never answer.
    max: 5,
    connectionTimeoutMillis: 15_000,
  });

  // Cast: the `SqlDriverAdapterFactory` type from `@prisma/client` can drift
  // from the copy bundled inside `@prisma/adapter-pg` (the provider union may
  // include engines this adapter does not implement). Runtime is unaffected.
  return new PrismaClient({ adapter: adapter as any });
}

/**
 * Returns the client for the current request, creating it on first use.
 *
 * Outside a request (scripts, `server.ts` local dev) this falls back to a
 * process-wide client, which is correct for plain Node.
 */
export function getPrisma(): PrismaClient {
  const scope = scopeStorage.getStore();

  if (scope) {
    if (!scope.client) {
      if (scope.disposed) {
        // Late work after the response was flushed. Warn and use the fallback
        // client rather than throwing inside an already-finished request.
        console.warn('⚠️ [PRISMA] Access after request scope was disposed; using fallback client');
        if (!_fallbackClient) _fallbackClient = createClient();
        return _fallbackClient;
      }
      scope.client = createClient();
    }
    return scope.client;
  }

  if (!_fallbackClient) _fallbackClient = createClient();
  return _fallbackClient;
}

/** Close everything (used by scripts / graceful shutdown in `server.ts`). */
export async function disconnectPrisma(): Promise<void> {
  const scope = scopeStorage.getStore();
  if (scope) {
    disposeScope(scope);
    return;
  }

  const client = _fallbackClient;
  _fallbackClient = null;
  if (client) await client.$disconnect();
}

/**
 * The `prisma` export that all route files import. A Proxy so that the actual
 * client (and therefore DATABASE_URL) is only resolved when a method is called,
 * never at module-import time.
 */
export const prisma: PrismaClient = new Proxy({} as PrismaClient, {
  get(_target, prop: string | symbol) {
    const client = getPrisma() as unknown as Record<string | symbol, unknown>;
    const value = client[prop];
    return typeof value === 'function' ? (value as Function).bind(client) : value;
  },
  has(_target, prop: string | symbol) {
    return prop in (getPrisma() as unknown as object);
  },
  ownKeys() {
    return Reflect.ownKeys(getPrisma() as unknown as object);
  },
  getOwnPropertyDescriptor(_target, prop: string | symbol) {
    return Object.getOwnPropertyDescriptor(getPrisma() as unknown as object, prop);
  },
}) as unknown as PrismaClient;

export default getPrisma;
